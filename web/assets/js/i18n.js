export const TRANSLATIONS = { en, ar };
export const LANGUAGES = [
  { id: 'en', label: 'English', dir: 'ltr' },
  { id: 'ar', label: 'العربية', dir: 'rtl' },
];

let current = 'en';

export function setLang(lang) {
  current = TRANSLATIONS[lang] ? lang : 'en';
  return current;
}

export function getLang() {
  return current;
}

export function dir(lang = current) {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

export function t(key, vars) {
  const table = TRANSLATIONS[current] || TRANSLATIONS.en;
  let value = table[key];
  if (value === undefined) value = TRANSLATIONS.en[key];
  if (value === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}

export function localizeName(record) {
  return current === 'ar' && record.nameAr ? record.nameAr : record.name;
}

export function localizeState(stateId) {
  const s = STATES_LOOKUP[stateId];
  if (!s) return stateId;
  return current === 'ar' ? s.ar : s.en;
}

